_BY_KEY = {t.key: t for t in TIERS}


def pick_tier(product_count: int | None) -> Tier:
    """Самый дешёвый тариф, лимит которого закрывает product_count."""
    if product_count is None:
        return TIERS[2]  # Хищник — разумный дефолт, если размер каталога неизвестен
    for tier in TIERS:
        if tier.limit is not None and product_count <= tier.limit:
            return tier
    return TIERS[-1]


def tier_by_key(key: str) -> Tier | None:
    return _BY_KEY.get(key)


def prev_tier(tier: Tier) -> Tier | None:
    idx = TIERS.index(tier)
    return TIERS[idx - 1] if idx > 0 else None


def discounted_price(price: int, discount_pct: int) -> int:
    return round(price * (100 - discount_pct) / 100)


def newcomer_terms(product_count: int) -> tuple[str, int, int]:
    """Тариф, первый оплаченный месяц и дальнейшая цена для новичка."""
    if 1 <= product_count <= 30:
        return "start", 1_000, 3_000
    if product_count <= 100:
        return "hunter", 3_000, 5_000
    if product_count <= 200:
        return "hunter", 5_000, 8_000
    raise ValueError("КП для новичков рассчитано на каталог от 1 до 200 товаров")
